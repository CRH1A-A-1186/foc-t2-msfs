# ---------------------------------------------------------------- utilities
def clear_scene():
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob, do_unlink=True)
    for me in list(bpy.data.meshes):
        if me.users == 0:
            bpy.data.meshes.remove(me)
    for mat in list(bpy.data.materials):
        if mat.users == 0:
            bpy.data.materials.remove(mat)

def make_mat(name, base, rough=0.85, metal=0.0, emission=None, alpha=1.0):
    m = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes.get('Principled BSDF')
    if bsdf:
        bsdf.inputs['Base Color'].default_value = (*base, 1.0)
        bsdf.inputs['Roughness'].default_value = rough
        bsdf.inputs['Metallic'].default_value = metal
        if emission:
            bsdf.inputs['Emission Color'].default_value = (*emission, 1.0)
            bsdf.inputs['Emission Strength'].default_value = 1.0
        if alpha < 1.0:
            bsdf.inputs['Alpha'].default_value = alpha
            m.surface_render_method = 'BLENDED'
    m.diffuse_color = (*base, alpha)
    return m

def new_obj(name, verts, faces, mat, collection='COL_Geo', smooth=0):
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False)
    bm = bmesh.new()
    bm.from_mesh(me)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bm.to_mesh(me)
    bm.free()
    me.update()
    ob = bpy.data.objects.new(name, me)
    col = bpy.data.collections.get(collection) or bpy.data.collections.new(collection)
    if col.name not in bpy.context.scene.collection.children:
        bpy.context.scene.collection.children.link(col)
    col.objects.link(ob)
    if mat:
        ob.data.materials.append(mat)
    if smooth:
        # the skin (top + bottom) is smooth, the eave rim stays flat -> crisp edge
        for i, p in enumerate(me.polygons):
            p.use_smooth = i < smooth
    return ob

def obj_from_bm(bm, name, mat, collection='COL_Ground', smooth=0):
    me = bpy.data.meshes.new(name)
    bmesh.ops.triangulate(bm, faces=bm.faces[:])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces[:])
    bm.to_mesh(me)
    bm.free()
    me.validate(verbose=False)
    me.update()
    ob = bpy.data.objects.new(name, me)
    col = bpy.data.collections.get(collection) or bpy.data.collections.new(collection)
    if col.name not in bpy.context.scene.collection.children:
        bpy.context.scene.collection.children.link(col)
    col.objects.link(ob)
    if mat:
        ob.data.materials.append(mat)
    if smooth:
        for i, p in enumerate(me.polygons):
            p.use_smooth = i < smooth
    return ob

def _clean(ring):
    r = [(float(x), float(y)) for x, y in ring]
    if len(r) > 2 and r[0] == r[-1]:
        r = r[:-1]
    return r

def flat_multi(entry, z, name, mat, collection='COL_Ground'):
    """Flat pavement polygon, honouring holes (entry: {'outer','holes'} or a bare ring).

    Holes are essential: the pavement layers are a partition (apron = apron - runway -
    taxiway), so the apron has holes where the taxiways cut through it.  Filling the
    holes re-covers the taxiway at the same z -> coplanar overlap -> z-fighting.
    Blender's beauty fill (triangle_fill) does the ring fill between outer and hole.
    """
    if isinstance(entry, dict):
        outer, holes = _clean(entry.get('outer') or []), [_clean(h) for h in (entry.get('holes') or [])]
    else:
        outer, holes = _clean(entry), []
    holes = [h for h in holes if len(h) >= 3]
    bm = bmesh.new()
    if not holes:
        vs = [bm.verts.new((x, y, z)) for x, y in outer]
        if len(vs) >= 3:
            try:
                bm.faces.new(vs)
            except ValueError:
                pass
    else:
        edges = []
        for lp in [outer] + holes:
            vs = [bm.verts.new((x, y, z)) for x, y in lp]
            for i in range(len(vs)):
                try:
                    edges.append(bm.edges.new((vs[i], vs[(i + 1) % len(vs)])))
                except ValueError:
                    pass
        try:
            bmesh.ops.triangle_fill(bm, use_beauty=True, use_dissolve=False, edges=edges)
        except Exception as ex:
            print('triangle_fill failed on %s: %s' % (name, ex))
        if not bm.faces:                      # fallback: plain n-gon of the outline
            vs = [bm.verts.new((x, y, z)) for x, y in outer]
            try:
                bm.faces.new(vs)
            except ValueError:
                pass
    return obj_from_bm(bm, name, mat, collection)

def flat_poly(ring, z, name, mat, collection='COL_Ground'):
    return flat_multi(ring, z, name, mat, collection)

def prism(ring, z0, z1, name, mat, collection='COL_Geo'):
    if ring[0] == ring[-1]:
        ring = ring[:-1]
    n = len(ring)
    z1v = z1 if isinstance(z1, (int, float)) else None
    verts = [(x, y, z0) for x, y in ring]
    verts += [(x, y, (z1 if z1v is not None else z1[i])) for i, (x, y) in enumerate(ring)]
    faces = [tuple(range(n - 1, -1, -1)), tuple(range(n, 2 * n))]
    for i in range(n):
        j = (i + 1) % n
        faces.append((i, j, n + j, n + i))
    return new_obj(name, verts, faces, mat, collection)

def strip(pts, width, z, name, mat):
    """Flat ribbon along a polyline."""
    verts, faces = [], []
    half = width / 2.0
    for i, p in enumerate(pts):
        if i == 0:
            d = Vector(pts[1]) - Vector(pts[0])
        elif i == len(pts) - 1:
            d = Vector(pts[-1]) - Vector(pts[-2])
        else:
            d = Vector(pts[i + 1]) - Vector(pts[i - 1])
        if d.length < 1e-9:
            d = Vector((1, 0))
        d.normalize()
        n = Vector((-d.y, d.x))
        p = Vector(p)
        verts.append((p.x + n.x * half, p.y + n.y * half, z))
        verts.append((p.x - n.x * half, p.y - n.y * half, z))
    for i in range(len(pts) - 1):
        a = 2 * i
        faces.append((a, a + 1, a + 3, a + 2))
    return new_obj(name, verts, faces, mat, 'COL_Markings')

