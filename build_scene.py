# ---------------- viewport clip for a 4.4 km scene
# Blender's factory viewport clip is 0.1 / 1000 m.  With a 4.4 km model that both
# cuts the model in half ("显示不全") and destroys depth precision at ~1 km, which
# shows up as z-fighting stripes between the pavement / terrain / glass / roof.
# These live in the View3D space, not the scene, so they must be written per area.
# Also park every viewport on the T2, otherwise a freshly opened file stares at the
# origin (the model sits ~250 m away) and looks empty.
def fix_view(start=1.0, end=80000.0, pivot=(256.0, 33.0, 20.0),
             dist=1500.0, direction=(0.891, -0.454, 0.55)):
    d = Vector(direction).normalized()
    q = (-d).to_track_quat('-Z', 'Y')
    n = 0
    for screen in bpy.data.screens:
        for area in screen.areas:
            for space in area.spaces:
                if space.type != 'VIEW_3D':
                    continue
                space.clip_start = start
                space.clip_end = end
                if space.overlay:
                    space.overlay.grid_scale = 100.0   # 1 m grid turns into dot noise at 1.5 km
                if space.region_3d:
                    space.region_3d.view_perspective = 'PERSP'
                    space.region_3d.view_location = pivot
                    space.region_3d.view_distance = dist
                    space.region_3d.view_rotation = q
                n += 1
    return n

